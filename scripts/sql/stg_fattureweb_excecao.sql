SELECT 
    TO_DATE(MES_DE_REFERENCIA_DA_FATURA, 'DD/MM/YYYY') AS MES_DE_REFERENCIA_DA_FATURA,
    TO_DATE(DATA_DE_EMISSAO_DA_FATURA, 'DD/MM/YYYY') AS DATA_DE_EMISSAO_DA_FATURA,
    DISTRIBUIDORA,
    NUMERO_DA_INSTALACAO,
    TO_DOUBLE(REPLACE(QUANTIDADE_CONSUMO_KWH, ',', '.')) AS QUANTIDADE_CONSUMO_KWH,
    TO_DOUBLE(REPLACE(QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_DE_31_ATE_100_KWH, ',', '.')) AS QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_DE_31_ATE_100_KWH,
    TO_DOUBLE(REPLACE(QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_ATE_30_KWH, ',', '.')) AS QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_ATE_30_KWH,
    TO_DOUBLE(REPLACE(QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_DE_101_ATE_220_KWH, ',', '.')) AS QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_DE_101_ATE_220_KWH,
    TO_DOUBLE(REPLACE(QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_SUPERIOR_A_220_KWH, ',', '.')) AS QUANTIDADE_CONSUMO_TE_TARIFA_SOCIAL_SUPERIOR_A_220_KWH,
    TO_DOUBLE(REPLACE(ALIQUOTA_PIS_PASEP, ',', '.')) AS ALIQUOTA_PIS_PASEP,
    TO_DOUBLE(REPLACE(ALIQUOTA_COFINS, ',', '.')) AS ALIQUOTA_COFINS,
    TO_DOUBLE(REPLACE(ALIQUOTA_ICMS, ',', '.')) AS ALIQUOTA_ICMS,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_BENEFICIO_TARIFARIO_BRUTO, ',', '.')) AS VALOR_TOTAL_BENEFICIO_TARIFARIO_BRUTO,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_BENEFICIO_TARIFARIO_LIQUIDO, ',', '.')) AS VALOR_TOTAL_BENEFICIO_TARIFARIO_LIQUIDO,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_CONTRIBUICAO_ILUMINACAO_PUBLICA, ',', '.')) AS VALOR_TOTAL_CONTRIBUICAO_ILUMINACAO_PUBLICA,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_DOACOES, ',', '.')) AS VALOR_TOTAL_DOACOES,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_COBRANCA_DE_TERCEIROS_NA_FATURA, ',', '.')) AS VALOR_TOTAL_COBRANCA_DE_TERCEIROS_NA_FATURA,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_RESTITUICAO_POR_PAGAMENTO_A_MAIOR, ',', '.')) AS VALOR_TOTAL_RESTITUICAO_POR_PAGAMENTO_A_MAIOR,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_MULTAS_JUROS_CORR_MONETARIA, ',', '.')) AS VALOR_TOTAL_MULTAS_JUROS_CORR_MONETARIA,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_MULTAS_JUROS_CORR_MONETARIA_DE_AJUSTES_DE_FATURAMENTO, ',', '.')) AS VALOR_TOTAL_MULTAS_JUROS_CORR_MONETARIA_DE_AJUSTES_DE_FATURAMENTO,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_DEBITOS_DE_SERVICOS_COBRAVEIS_PELA_DISTRIBUIDORA, ',', '.')) AS VALOR_TOTAL_DEBITOS_DE_SERVICOS_COBRAVEIS_PELA_DISTRIBUIDORA,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_PARCELAMENTOS, ',', '.')) AS VALOR_TOTAL_PARCELAMENTOS,
    TO_DOUBLE(REPLACE(VALOR_TOTAL_BONUS_ITAIPU, ',', '.')) AS VALOR_TOTAL_BONUS_ITAIPU,
    TIPO_LIGACAO,
    CASE
        WHEN TIPO_LIGACAO = 'MONOFÁSICO' THEN 30
        WHEN TIPO_LIGACAO = 'BIFÁSICO' THEN 50
        WHEN TIPO_LIGACAO = 'TRIFÁSICO' THEN 100
    END AS CONSUMO_BASE,
    CASE
        WHEN
            CLASSIFICACAO ILIKE '%baixa renda%'
        THEN 'BAIXA RENDA'
        WHEN
            VALOR_TOTAL_BENEFICIO_TARIFARIO_BRUTO IS NOT NULL
        THEN 'GD2'
        WHEN
            MODALIDADE_TARIFARIA = 'BRANCA'
        THEN 'TARIFA BRANCA'
        WHEN
            SUBGRUPO = 'A4'
        THEN 'ALTA TENSAO'
        ELSE 'CONVENCIONAL'
    END AS TIPO_FATURA
FROM RETAIL_DEV.BACKOFFICE.FATTUREWEB_FATURAMENTO
where tipo_fatura <> 'CONVENCIONAL';